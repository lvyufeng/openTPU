  function automatic logic signed [14:0] ternary_dot8(input logic [63:0] grid_v,
                                                       input logic [63:0] act_v);
    logic signed [11:0] x;
    logic signed [14:0] acc;
    acc = 15'sd0;
    for (int j = 0; j < 8; j++) begin
      x = signed'({{4{act_v[8 * j + 7]}}, act_v[8 * j +: 8]});
      if (grid_v[8 * j +: 8] == 8'hff)
        acc = acc - 15'(x);
      else if (grid_v[8 * j +: 8] == 8'h01)
        acc = acc + 15'(x);
    end
    ternary_dot8 = acc;
  endfunction
  function automatic logic signed [14:0] activation_sum8(input logic [63:0] act_v);
    logic signed [14:0] acc;
    acc = 15'sd0;
    for (int j = 0; j < 8; j++)
      acc = acc + 15'(signed'({{7{act_v[8 * j + 7]}}, act_v[8 * j +: 8]}));
    activation_sum8 = acc;
  endfunction
