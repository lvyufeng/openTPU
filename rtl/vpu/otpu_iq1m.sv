// IQ1_M, 56 bytes / 256 ternary weights: qs[0:32], qh[32:48], scales[48:56].
// There is NO contiguous d field.  Its fp16 bits are the high nibbles of four
// little-endian scale words (high nibble of bytes 49,51,53,55 forms d[3:0],
// d[7:4], d[11:8], d[15:12]).  The other scale fields are two 6-bit pairs;
// ls1/ls2 are 2*(three-bit field)+1.  qh[2g + l/2] contributes three high index
// bits (bits 2:0 or 6:4), plus one delta sign (bit 3 or 7).  A set delta sign
