// grp_bsum is ls1*signed-grid-dot(l0,l1) + ls2*...(l2,l3), and grp_aux is the
// corresponding integer DELTA term.  Keep them separate: the caller accumulates
// both totals then applies d * (total_grid + 0.125 * total_delta).  There is NO
// additional outer 0.125.  Integer ternary values here are {-1,0,+1}, read as
// int8; do not use IQ1S's GPU-biased nibble table.
// Seven weight beats + eight 256-bit activation beats = 15 accepted cycles.
// Per group either term is bounded by 15 * 2 * 16 * 128 = 61440 (int17); the
// datapath uses int21 deliberately.  Reference: ggml-cpu/quants.c:1193-1252,
