"""IQ2_XXS / IQ1_M codebooks as copied, little-endian byte data (MIT).

This file holds *data, not executable code*: the ``kmask_iq2xs``,
``ksigns_iq2xs``, ``iq2xxs_grid`` and ``iq1s_grid`` tables copied verbatim from
pinned MIT-licensed ggml/Strata headers, plus a structural, sortedness and
SHA-256 validation of their exact bytes.  No quantization, dequantization or
dot algorithm is copied here; the group-unpacking and dot mathematics live in
``tools/iq_multi_rtl_check.py`` (Apache-2.0, an independent transcription of
ggml's documented byte layout).

The ``iq2s_grid`` table is deliberately **not** duplicated here: this tree
already carries it in ``tools/iq_rtl_check.py`` (``IQ2S_GRID``) and so this
module re-exports that one object instead of keeping a second copy.

Provenance
----------
Copied as little-endian bytes from the Strata distribution at the locked
revision ``3142b66b96e9c0e775e30f620b11b191a1427c2a``, where they are
byte-identical to the integration inventory at
``97affb754d298b2cce1fc7b12338797ac155aa9b``:

* ``engine/include/strata/quant/strata-quant-common.h``
  (SHA256 ``0709a7a826c1c8c73d814b8362818b6108d37c119257b97df9824b3053d08a1a``):
  - ``kmask_iq2xs``   lines 499-501   (8 bytes, values ``1 << j``)
  - ``ksigns_iq2xs``  lines 504-513   (128 bytes, ``GGML_TABLE_BEGIN(uint8_t, ...)``)
  - ``iq2xxs_grid``   lines 552-617   (256 x uint64, ``GGML_TABLE_BEGIN(uint64_t, ...)``)
  - ``iq1s_grid``     lines 1133-1646 (2048 x uint64, ``NGRID_IQ1S`` = 2048)

* ``engine/third_party/strata-llama/ggml/src/ggml-common.h``
  (SHA256 ``0061131b615c5721fc88a78feeb22c1f8c450f1c2646a317d80796a653bf595c``):
  the same four tables byte for byte (``kmask_iq2xs`` lines 509-511 ...
  ``iq1s_grid`` lines 1129-1642), derived from ggml/llama.cpp
  ``3cf03257f219afbe7334045ff7c6a06ac68c627d``.

Only the scalar tables are copied.  The GPU-only ``iq1s_grid_gpu`` table (a
different ``uint32_t`` "value + 1 in 4-bit fields" encoding) and ``iq2s_grid``
are not copied into this file.

Modification record (2026-11-24, lvyufeng and the openTPU contributors)
-----------------------------------------------------------------------
1. Extracted the four tables retained here once, mechanically, from the
   committed oracle copy of the pinned tables (provenance above); the module
   has no runtime import, path lookup or dependency on that tool.
2. Split each 64-bit grid word into eight byte lanes and stored the lanes as
   ``bytes``, preserving little-endian lane order, so that the copied data is
   the exact byte sequence the C headers declare.  ``kmask_iq2xs`` is derived
   as ``bytes(1 << j)``.  Values are otherwise unmodified.
3. Added import-time structural checks, a byte-alphabet sort check for the
   two grids (the sequences must equal their own sorted byte keys) and a
   SHA-256 over the *actual* table bytes in this file; nothing trusts a
   hard-coded source file.  ``grid_bytes`` / ``grid_signed`` perform only the
   C view of each word.
4. Exposed ``IQ2S_GRID`` / ``GRID_SHA256`` re-exports from ``iq_rtl_check``
   instead of carrying a second copy of ``iq2s_grid``.

The tables are MIT data and are not relicensed by openTPU's Apache-2.0
license.  Complete notices: as above; see also ``tools/packed_oracle/
ATTRIBUTION.md`` and ``licenses/`` in that package for the identical
``GGML-MIT.txt`` / ``STRATA-MIT.txt`` text.

Layout
------
``IQ2XXS_GRID_BYTES`` 256 * 8 bytes, ``IQ1S_GRID_BYTES`` 2048 * 8 bytes,
``KSIGNS_IQ2XS_BYTES`` 128 bytes, ``KMASK_IQ2XS_BYTES`` 8 bytes.  The same
words are also available as integer tuples (``IQ2XXS_GRID``, ``IQ1S_GRID``)
alongside the raw byte blobs (``IQ2XXS_GRID_RAW``, ``IQ1S_GRID_RAW``),
which are the objects the SHA-256 values cover.
"""

