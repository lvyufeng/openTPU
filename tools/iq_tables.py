def grid_bytes(word: int) -> tuple[int, ...]:
    """Return the eight little-endian unsigned bytes of one 64-bit grid word."""
    if not 0 <= word < (1 << 64):
        raise ValueError("grid words are 64-bit")
    return tuple((word >> (8 * lane)) & 0xFF for lane in range(8))


def grid_signed(word: int) -> tuple[int, ...]:
    """Return the eight little-endian int8 lanes of one 64-bit grid word (IQ1_M)."""
    return tuple(byte - 256 if byte >= 128 else byte for byte in grid_bytes(word))


