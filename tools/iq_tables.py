def _check_kmask() -> None:
    if KMASK_IQ2XS_BYTES != bytes((1, 2, 4, 8, 16, 32, 64, 128)):
        raise AssertionError("kmask_iq2xs must be the eight single-bit masks")
    if any(KMASK_IQ2XS_BYTES[j] != 1 << j for j in range(8)):
        raise AssertionError("kmask_iq2xs[j] must be 1 << j")


def _check_ksigns() -> None:
    if len(KSIGNS_IQ2XS_BYTES) != NSIGNS_IQ2XS:
        raise AssertionError("ksigns_iq2xs must be 128 bytes")
    # Patterns 4i..4i+3 differ only in their two low bits; the table is a fixed
    # enumeration, so no additional structure is assumed beyond the byte range.


def _check_grid(
    name: str,
    raw: bytes,
    count: int,
    alphabet: tuple[int, ...],
    words: tuple[int, ...] | None = None,
    sorted_by_word: bool = True,
) -> None:
    if len(raw) != 8 * count:
        raise AssertionError(f"{name} must be {count} 64-bit words")
    allowed = set(alphabet)
    for lane in range(8):
        bad = sorted(set(raw[lane::8]) - allowed)
        if bad:
            raise AssertionError(f"{name} lane {lane} has unexpected bytes {bad}")
    rows = [raw[8 * i : 8 * i + 8] for i in range(count)]
    if len(set(rows)) != count:
        raise AssertionError(f"{name} contains duplicate rows")
    # ggml sorts the IQ2 grids digit by digit over the C hex literal, i.e. lane 0
    # first: the sequence equals the sorted order of the reversed-byte rows.
    if sorted_by_word and [row[::-1] for row in rows] != sorted(
        row[::-1] for row in rows
    ):
        first = next(
            i for i in range(count - 1) if rows[i][::-1] > rows[i + 1][::-1]
        )
        raise AssertionError(
            f"{name} is not sorted by lane-0-first byte key at entry {first}"
        )
    if words is not None and tuple(
        int.from_bytes(row, "little") for row in rows
    ) != tuple(words):
        raise AssertionError(f"{name} words do not round-trip through the bytes")


def _check_tables() -> None:
    """Fail loudly at import time if the copied data is wrong in any way."""
    _check_kmask()
    _check_ksigns()
    _check_grid(
        "iq2xxs_grid", IQ2XXS_GRID_BYTES, NGRID_IQ2XXS, IQ2_GRID_MAGNITUDES,
        IQ2XXS_GRID,
    )
    # iq1s_grid is not in sorted row order upstream; it is only required to be
    # unique and ternary per lane.
    _check_grid(
        "iq1s_grid", IQ1S_GRID_BYTES, NGRID_IQ1S, IQ1S_GRID_BYTES_ALPHABET,
        IQ1S_GRID, sorted_by_word=False,
    )
    if tuple(IQ2XXS_GRID_BYTES) != tuple(
        b for word in IQ2XXS_GRID for b in grid_bytes(word)
    ):
        raise AssertionError("iq2xxs_grid words do not round-trip through the bytes")
    if tuple(IQ1S_GRID_BYTES) != tuple(
        b for word in IQ1S_GRID for b in grid_bytes(word)
    ):
        raise AssertionError("iq1s_grid words do not round-trip through the bytes")
    for lane in range(8):
        values = {grid_signed(IQ1S_GRID[i])[lane] for i in range(NGRID_IQ1S)}
        if not values <= set(IQ1S_GRID_VALUES):
            raise AssertionError("iq1s_grid lanes must be ternary")
    if sorted(set(IQ2XXS_GRID_BYTES)) != list(IQ2_GRID_MAGNITUDES):
        raise AssertionError("iq2xxs_grid must use the full (8, 25, 43) alphabet")
    if sorted(set(IQ1S_GRID_BYTES)) != list(IQ1S_GRID_BYTES_ALPHABET):
        raise AssertionError("iq1s_grid must use all three ternary bytes")
    actual = sha256_tables()
    for name, want in IQ_TABLE_SHA256.items():
        if actual[name] != want:
            raise AssertionError(f"{name} sha256 {actual[name]} != pinned {want}")


